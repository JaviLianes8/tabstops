"""Generate the display width table from the fetched UCD files.

Usage::

    python scripts/gen_width_table.py            # rewrite src/tabstops/_width_data.py
    python scripts/gen_width_table.py --check    # exit 1 if the file is stale

Inputs live in ``data/ucd/``, which git ignores: ``python scripts/fetch_upstream.py``
fetches them as pinned in ``data/ucd/MANIFEST.json``. Every code point gets a class:
0 (no advance), 1 (narrow), 2 (wide) or 3 (East Asian Ambiguous). The table is the run
lengths of those classes over the whole code space, each run written as its class digit
followed by its length in base 36.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UCD_DIR = ROOT / "data" / "ucd"
TARGET = ROOT / "src" / "tabstops" / "_width_data.py"
VERSION = "18.0.0"
SIZE = 0x110000
LINE_WIDTH = 88
DIGITS = "0123456789abcdefghijklmnopqrstuvwxyz"
LONG_EAW = {"Neutral": "N", "Wide": "W", "Fullwidth": "F", "Ambiguous": "A"}

_LINE = re.compile(r"^(?:# @missing: )?([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*(\w+)")


def _ranges(name: str) -> list[tuple[int, int, str]]:
    """Return ``(first, last, value)`` for each data line, ``@missing`` defaults first."""
    defaults: list[tuple[int, int, str]] = []
    explicit: list[tuple[int, int, str]] = []
    for line in (UCD_DIR / name).read_text(encoding="utf-8").splitlines():
        match = _LINE.match(line)
        if match:
            first = int(match.group(1), 16)
            last = int(match.group(2) or match.group(1), 16)
            target = defaults if line.startswith("#") else explicit
            target.append((first, last, match.group(3)))
    return defaults + explicit


def _matching(name: str, values: set[str]) -> list[tuple[int, int]]:
    return [(first, last) for first, last, value in _ranges(name) if value in values]


def classes() -> bytearray:
    """Return the width class of every code point."""
    table = bytearray([1]) * SIZE
    for first, last, value in _ranges("DerivedEastAsianWidth.txt"):
        code = {"W": 2, "F": 2, "A": 3}.get(LONG_EAW.get(value, value), 1)
        table[first : last + 1] = bytes([code]) * (last - first + 1)
    zero = (
        _matching("DerivedGeneralCategory.txt", {"Mn", "Me", "Cc"})
        + _matching("DerivedCoreProperties.txt", {"Default_Ignorable_Code_Point"})
        + _matching("HangulSyllableType.txt", {"V", "T"})
    )
    for first, last in zero:
        table[first : last + 1] = bytes(last - first + 1)
    return table


def _base36(value: int) -> str:
    out = ""
    while True:
        value, digit = divmod(value, 36)
        out = DIGITS[digit] + out
        if not value:
            return out


def render() -> str:
    """Return the source of the generated module."""
    table = classes()
    tokens: list[str] = []
    start = 0
    for index in range(1, SIZE + 1):
        if index == SIZE or table[index] != table[start]:
            tokens.append(f"{table[start]}{_base36(index - start)}")
            start = index
    lines: list[str] = []
    current = ""
    for token in tokens:
        if len(current) + len(token) + 1 > LINE_WIDTH - 6:
            lines.append(current)
            current = ""
        current = f"{current} {token}" if current else token
    lines.append(current)
    body = "\n".join(f'    "{line} "' for line in lines)
    return (
        '"""Display width classes of every code point, as run lengths."""\n\n'
        "# Generated by scripts/gen_width_table.py from data/ucd/. Do not edit.\n\n"
        "from __future__ import annotations\n\n"
        f'UNICODE_VERSION = "{VERSION}"\n'
        "RUNS = (\n"
        f"{body}\n"
        ")\n"
    )


def _verify() -> list[str]:
    """Return the problems with the local files: missing, or not the pinned bytes."""
    manifest = json.loads((UCD_DIR / "MANIFEST.json").read_text(encoding="utf-8"))
    problems = []
    for name, entry in manifest.items():
        path = UCD_DIR / name
        if not path.is_file():
            problems.append(f"{name} is missing")
        elif hashlib.sha256(path.read_bytes()).hexdigest() != entry["sha256"]:
            problems.append(f"{name} differs from the sha256 in MANIFEST.json")
    return problems


def main(argv: list[str]) -> int:
    problems = _verify()
    if problems and "--check" in argv and all(p.endswith("missing") for p in problems):
        print("SKIPPED: data/ucd/ is not fetched; run python scripts/fetch_upstream.py")
        return 0
    if problems:
        print("\n".join(problems))
        return 1
    source = render()
    if "--check" in argv:
        if TARGET.read_text(encoding="utf-8") != source:
            print(f"{TARGET.name} is stale; run python scripts/gen_width_table.py")
            return 1
        print(f"{TARGET.name} is up to date")
        return 0
    TARGET.write_text(source, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
